"""Generate API authentication/ownership evidence from route and helper source (no DB access)."""
import argparse
import ast
import json
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]


def inventory():
    rows = []
    # main.py가 include_router하는 모듈을 모두 표에 넣는다. 새 라우터가 표에서 빠지지 않게 한다.
    main_source = (ROOT / "backend" / "main.py").read_text(encoding="utf-8")
    routers = re.findall(r"^from (\w+) import router as \w+\s*$", main_source, re.M)
    for filename, prefix in [(name + ".py", "") for name in ["main", *routers]]:
        source = (ROOT / "backend" / filename).read_text(encoding="utf-8")
        tree = ast.parse(source)
        functions = {n.name: n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))}
        for node in functions.values():
            for dec in node.decorator_list:
                if not isinstance(dec, ast.Call) or not isinstance(dec.func, ast.Attribute) or dec.func.attr not in {"get", "post", "patch", "delete", "put", "options", "head"}:
                    continue
                if not dec.args or not isinstance(dec.args[0], ast.Constant):
                    continue
                path = prefix + dec.args[0].value
                if not path.startswith("/api") and path != "/health":
                    continue
                seen = set()
                def closure(fn):
                    if fn.name in seen: return ""
                    seen.add(fn.name)
                    text = ast.get_source_segment(source, fn)
                    for call in ast.walk(fn):
                        if isinstance(call, ast.Call) and isinstance(call.func, ast.Name) and call.func.id in functions:
                            text += "\n" + closure(functions[call.func.id])
                    return text
                evidence = closure(node)
                own = []
                for line in evidence.splitlines():
                    if any(x in line for x in (".user_id ==", "user_id=current_user.id", "user_id=user.id", "_battery_session(", "_COACH_JOBS.get(", "SESSIONS.get(", "_pop_speak_stream(", "require_admin(", "_require_admin(")):
                        own.append(line.strip())
                auth = "Bearer" if "Depends(get_current_user)" in evidence else "optional/manual Bearer" if "get_current_user(" in evidence else "public"
                admin = any(x in evidence for x in ("require_admin(", "_require_admin(", "LIPLAB_ADMIN_EMAILS", "_admin_email_gate(", "_pilot_admin_gate(", "_review_gate("))
                if "current_user.id" in evidence or "user.id" in evidence:
                    own.append("JWT principal supplies user scope (inspect helper evidence)")
                rows.append(dict(method=dec.func.attr.upper(), path=path, auth=auth, admin=admin,
                    evidence=list(dict.fromkeys(own)), source=f"backend/{filename}:{node.lineno}"))
    return sorted(rows, key=lambda r: (r["path"],r["method"]))


def markdown(rows):
    lines = ["# API authentication and ownership inventory", "", "Generated by `python scripts/api_security_inventory.py`. Source evidence is a review aid, not a proof of authorization. Shared content IDs are not private object IDs; IDOR fixtures are in `backend/test_security3.py`.", "", "| Method | Route | Authentication | Administrator | Ownership source evidence |", "|---|---|---|---|---|"]
    for r in rows:
        e = "<br>".join(x.replace("|", "&#124;") for x in r["evidence"]) or "No direct ownership expression; review helper/current-user scope or shared content"
        lines.append(f"| {r['method']} | `{r['path']}` | {r['auth']} | {'yes' if r['admin'] else 'no'} | {e} ({r['source']}) |")
    return "\n".join(lines) + "\n"

if __name__ == "__main__":
    p=argparse.ArgumentParser(); p.add_argument("--check",action="store_true"); a=p.parse_args()
    target=ROOT/"docs/api-security-inventory.md"; content=markdown(inventory())
    if a.check:
        assert target.read_text(encoding="utf-8")==content, "Regenerate API security inventory"
    else:
        target.write_text(content,encoding="utf-8")
    print(f"{len(inventory())} routes inventoried")
