// 입모양 하나를 되풀이해 보여 줄 때의 순서(1단계 입모양 인지·입모양 복습). 기본은 중립(15) ↔ 목표.
// 이중모음(9)은 레슨이 '입모양이 움직이는 것이 단서, 한 컷이 아니라 변화를 읽는다'고 가르치는데, 예전에는 원순모음(4)과 비슷한
// 정지 모양 하나(거리 0.31)로만 보여 줘 4와 헷갈렸다. 대표 음절 '와'처럼 원순(4)에서 개방(2)으로 미끄러지는 움직임을 보인다.
// 각 단계: v 입모양, ms 머무는 시간, t 그 입모양으로 옮기는 전환 시간(AvatarVRM transitionMs).
export function visemeCycleSteps(visemeId) {
  if (visemeId === 9) {
    return [{ v: 4, ms: 320, t: 160 }, { v: 2, ms: 560, t: 200 }, { v: 15, ms: 450, t: 220 }]
  }
  return [{ v: visemeId ?? 15, ms: 850, t: 220 }, { v: 15, ms: 450, t: 220 }]
}
